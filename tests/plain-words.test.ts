import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

// Сторож словаря: приложение говорит с человеком на его языке, а не на нашем.
//
// «Книга» — слово из головы того, кто это писал. Человек, скачавший приложение
// для учёта расходов, видит «Защитите книгу паролем» и не понимает ни о какой
// книге речь: он завёл счёт и пару операций, книг у него нет. Владелец
// сформулировал это прямо: защита ставится на ДАННЫЕ.
//
// Вместе с «книгой» из текстов ушли «ячейка» и «билет». Они жили не в каталоге,
// а в сообщениях об ошибках — то есть попадались человеку ровно в тот момент,
// когда что-то сломалось и меньше всего хотелось разгадывать чужие слова.
// «Не отдаёт ячейку» не говорит ни о чём никому, кроме того, кто писал слой
// синхронизации.
//
// Сторож смотрит на ИСХОДНИК, а не на экран: перебирать полтора десятка экранов
// проверками бессмысленно — новая строка с «книгой» появится в семнадцатом.
// Внутри кода, в именах и комментариях, эти слова остаются: там они точны и
// читаются теми, кому адресованы.

/** Где лежит то, что человек читает глазами. */
const SPOKEN = [
  "lib/i18n/catalog.ts",
  "lib/vault/account.ts",
  "lib/vault/server-account.ts",
  "lib/storage/EncryptingStorageAdapter.ts",
  "lib/sync/vault-crypto.ts",
  "lib/sync/HttpSyncTransport.ts",
  "lib/api/LocalApiClient.ts"
];

/**
 * Слова, которых в речи приложения быть не должно, и чем они плохи.
 *
 * Причина у каждого своя, и она записана здесь же: список без причин через
 * полгода станет списком запретов без объяснений, и первый же человек, которому
 * слово понадобится по делу, снимет строку, не зная, что снимает.
 */
const JARGON: Record<string, string> = {
  книг: "человек ведёт расходы, а не книгу — защита ставится на данные",
  ячейк: "имя из слоя синхронизации; человеку оно не говорит ничего",
  билет: "то же самое про вход: человек знает «подключиться», а не «билет»",
  шкатулк: "наше слово для хранилища ключа; наружу ему нельзя"
};

/**
 * Строки в кавычках — и только они.
 *
 * Комментарии и имена переменных берут те же слова законно: там «ячейка» —
 * точное имя того, что лежит на сервере, и переименовывать его в «данные»
 * значило бы сделать код хуже ради проверки. Человеку видно содержимое кавычек,
 * его и смотрим.
 */
export function spokenText(source: string): string[] {
  const withoutLineComments = source.replace(/^\s*\/\/.*$/gm, "");
  const withoutBlockComments = withoutLineComments.replace(/\/\*[\s\S]*?\*\//g, "");
  return [...withoutBlockComments.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((hit) => hit[1]);
}

describe("приложение говорит по-человечески", () => {
  it("кавычки отделяются от комментариев", () => {
    // Сама проверка проверяема: сними отсечение комментариев — и сторож начнёт
    // краснеть на честном пояснении в коде, а починят его, сняв сторожа.
    const sample = '// про книгу в комментарии\nconst a = "про данные";\n';
    expect(spokenText(sample)).toEqual(["про данные"]);
  });

  it("в речи нет наших слов", () => {
    const found: string[] = [];

    for (const file of SPOKEN) {
      const source = readFileSync(file, "utf8");
      for (const line of spokenText(source)) {
        const lower = line.toLowerCase();
        for (const [word, why] of Object.entries(JARGON)) {
          // Словарь кода восстановления — двенадцать обычных русских слов, и
          // «книга» среди них просто слово, а не наше понятие.
          if (file.endsWith("recovery-words.ts")) continue;
          if (lower.includes(word)) found.push(`${file}: «${line.slice(0, 60)}» — ${why}`);
        }
      }
    }

    expect(found, "наши слова в речи приложения").toEqual([]);
  });
});
