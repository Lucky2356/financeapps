/**
 * Документ состояния внутри того, что лежит в файле.
 *
 * Резервную копию в приложении пишут три места: кнопка «выгрузить» кладёт сам
 * документ, а копия по расписанию и копия в папку заворачивают его в
 * `{ exportedAt, backup }`. Восстановление понимало только первое — и файл от
 * двух других открывался со всеми нулями, а потом отвергался. То есть ровно
 * тот файл, который человек берёт с собой на второй компьютер.
 *
 * Живёт отдельно, потому что читают его теперь двое: экран импорта и первый
 * запуск, где «восстановить из файла» — один из трёх способов начать. Разойдись
 * они в понимании того, что лежит в файле, — и один принимал бы то, что другой
 * отвергает, на одном и том же файле.
 */
export function unwrapBackup(payload: unknown): unknown {
  const data = payload as { backup?: unknown } | null;
  return data && typeof data === "object" && data.backup && typeof data.backup === "object"
    ? data.backup
    : payload;
}
