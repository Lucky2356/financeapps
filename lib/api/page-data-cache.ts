// Последний посчитанный ответ по каждому маршруту, на время жизни окна.
//
// Экраны собираются статическим экспортом, поэтому оболочка, которую отдаёт
// сборка, всегда пустая (см. lib/data.ts): числа приходят позже, из IndexedDB.
// Пока их нет, экран показывает нули — и делал это на КАЖДОМ переходе, включая
// возврат туда, где только что был. Считается это быстро (главный экран на
// книге в 5000 операций — 17 мс), но между отрисовкой пустой оболочки и
// подстановкой чисел всё равно есть кадр, и он читается как «подтормаживает».
//
// Здесь ровно одна карта «маршрут → последний ответ». Экран, который уже
// открывали, рисуется сразу этими числами, а свежие подставляются в место,
// когда придут. Ошибиться тут трудно: это не хранилище, а память об уже
// показанном.
//
// Живёт в памяти вкладки и намеренно не переживает перезапуск: на диске
// единственным источником правды остаётся сама книга, и второй копии,
// способной с ней разойтись, заводить не стоит.
const lastSeen = new Map<string, unknown>();

/** Что показывали на этом маршруте в прошлый раз, если показывали. */
export function readPageData<T>(path: string): T | undefined {
  return lastSeen.get(path) as T | undefined;
}

/** Запомнить ответ, чтобы следующий приход на маршрут был мгновенным. */
export function writePageData<T>(path: string, data: T): void {
  lastSeen.set(path, data);
}

/**
 * Забыть всё. Нужно там, где книга перестаёт быть той же самой: восстановление
 * из копии, переключение профиля, очистка хранилища. Оставить память об экранах
 * прежнего профиля значило бы показать чужие числа — пусть на один кадр, но
 * в приложении про деньги и один кадр лишний.
 */
export function clearPageData(): void {
  lastSeen.clear();
}
