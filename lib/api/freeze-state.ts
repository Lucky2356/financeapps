// Растяжка вокруг книги, которую держит в памяти LocalApiClient.
//
// Чтения намеренно отдают кэш как есть, без копии: копировать книгу на каждое
// открытие экрана дороже, чем всё, что экран потом с ней делает. Плата за это
// — договор: возвращённое трогать нельзя. Сегодня его никто не нарушает — ни
// обработчики, ни записи, ни экраны, — но держится это на внимательности, а
// цена ошибки высокая: испорченная в памяти книга уедет на диск следующим же
// сохранением, и человек увидит остаток, которого нет.
//
// Поэтому вне поставки книга замораживается вглубь. Сегодня это ничего не
// меняющая проверка, а первая же попытка что-то в ней переставить станет
// исключением — и упадёт она на 669 модульных тестах и 161 сценарии e2e, то
// есть до выпуска, а не у человека. В поставке приложение за это не платит
// ничего: там заморозки нет.
//
// Почему не копировать на чтении: это отменило бы измеренную оптимизацию —
// половину времени открытия экрана — ради опасности, которой пока нет.

/** Замораживает объект и всё, что внутри. Циклы не обходит: их в книге нет. */
function freezeDeep<T>(value: T, seen: WeakSet<object>): T {
  if (value === null || typeof value !== "object") return value;
  if (seen.has(value as object)) return value;
  seen.add(value as object);

  for (const nested of Object.values(value as Record<string, unknown>)) {
    freezeDeep(nested, seen);
  }
  return Object.freeze(value);
}

/**
 * Вне поставки — замороженная вглубь книга, в поставке — она же без изменений.
 *
 * Проверяется NODE_ENV, а не флаг приложения: под ним ходят и `vitest`, и
 * `next dev`, и сборка e2e, то есть ровно те прогоны, где ошибку и надо
 * поймать.
 */
export function freezeLedgerOutsideProduction<T>(state: T): T {
  if (process.env.NODE_ENV === "production") return state;
  return freezeDeep(state, new WeakSet());
}
