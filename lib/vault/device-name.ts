/**
 * Как это устройство назовётся в списке устройств учётной записи.
 *
 * Догадка по строке браузера, и догадка грубая: два компьютера с Windows
 * получат одно и то же имя и станут неразличимы. Переименование — отдельная
 * работа; пока честнее назвать хоть как-то, чем не назвать никак: список
 * устройств человеку нужен ровно затем, чтобы выкинуть потерянный телефон.
 *
 * Живёт отдельно, потому что подключиться к службе теперь можно из двух мест:
 * из настроек и с первого запуска. Скопируй мы эти четыре строки во второе
 * место — и одно устройство называлось бы по-разному в зависимости от того,
 * откуда человек подключился.
 */
export function deviceName(): string {
  if (typeof navigator === "undefined") return "Устройство";
  const agent = navigator.userAgent;
  if (/Android/i.test(agent)) return "Телефон (Android)";
  if (/Windows/i.test(agent)) return "Компьютер (Windows)";
  if (/Mac OS/i.test(agent)) return "Компьютер (Mac)";
  return "Устройство";
}
