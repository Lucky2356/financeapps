// Какие два слова кода восстановления спросить обратно при первом запуске.
//
// Отдельным модулем, а не строчкой в экране: это чистый расчёт, и в прошлый
// раз он оказался неверным именно потому, что жил внутри разметки и проверить
// его было нечем.
//
// Первая попытка считала второе слово ОТ ПЕРВОГО:
//
//     const first  = a % (total - 1);
//     const second = first + 1 + (b % (total - first - 1));
//
// Выглядит как «два разных по возрастанию» и им и является — но раздаёт слова
// как попало: вторым никогда не выпадает слово под первым номером, а чем ближе
// первое к концу списка, тем меньше остаётся места второму. Замер на 300 000
// бросков: одно слово доставалось в 4,5 % случаев, другое в 13,7 % — втрое
// чаще, при ровной доле 8,3 %. Ошибку показал разбор кода (CodeQL), указав на
// остаток от деления; настоящая была рядом и крупнее.

/**
 * Равновероятное число от 0 до `limit` − 1.
 *
 * Отсечением лишнего, а не остатком от деления: 2³² на 11 нацело не делится, и
 * остаток сам по себе делает начало диапазона чуть вероятнее конца. Здесь это
 * не тайна, а всего лишь порядок вопросов, — но одинаковое отношение к
 * случайности во всём коде стоит дешевле, чем два разных, из которых однажды
 * выберут не то. Тем же приёмом собирается и сам код восстановления.
 */
export function randomBelow(limit: number): number {
  const mask = (1 << (32 - Math.clz32(limit - 1))) - 1;
  const draw = new Uint32Array(1);
  let value: number;
  do {
    crypto.getRandomValues(draw);
    value = draw[0] & mask;
  } while (value >= limit);
  return value;
}

/** Два разных номера слова из `total`, по возрастанию. */
export function pickTwo(total: number): [number, number] {
  // Тянем, пока не выпадут разные, и раскладываем по порядку. Считать второе
  // от первого короче — и как раз на этой арифметике перекос и заводится.
  const first = randomBelow(total);
  let second = randomBelow(total);
  while (second === first) second = randomBelow(total);
  return first < second ? [first, second] : [second, first];
}
