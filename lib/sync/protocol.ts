// Договор обмена между устройством и сервером.
//
// Отдельным файлом и раньше самой синхронизации — нарочно. Это единственное
// место, где написано, что именно ездит по проводу; служба на сервере (06.6)
// будет писаться по нему же, и разойтись им негде. Пока сервера нет, договор
// исполняет поддельный сервер в проверках — тот, что в tests/helpers.
//
// Главное свойство договора: СЕРВЕР НЕ ВИДИТ СОДЕРЖИМОГО. По проводу ездит
// SealedBook — та же шкатулка, что лежит на диске, зашифрованная ключом книги,
// которого у сервера нет и быть не может. Поэтому здесь нет ни одного поля,
// в которое можно было бы заглянуть: ни сумм, ни названий счетов, ни числа
// операций. Сервер знает только «чья ячейка», «какой она версии» и «когда её
// трогали в последний раз».
//
// Второе свойство: ЗАПИСЬ ТОЛЬКО ПОВЕРХ ИЗВЕСТНОЙ ВЕРСИИ. Устройство,
// отправляя книгу, предъявляет номер версии, поверх которой пишет. Совпало —
// сервер принял и выдал следующий номер. Не совпало — сервер отказал и вернул
// то, что у него есть. Без этого правила два устройства, вышедшие в сеть
// одновременно, затёрли бы работу друг друга молча, и узнать об этом было бы
// нечем и неоткуда. Отказ — это не ошибка, а нормальный ход: с него начинается
// слияние.

import type { SealedBook } from "@/lib/sync/vault-crypto";

/**
 * Ячейка на сервере — одна на каждый ключ хранилища, который синхронизируется.
 *
 * Ключом ячейки служит имя ключа в хранилище устройства (`localFinanceState_…`,
 * `profileList`). Имена не шифруются — шифруется содержимое, — и это осознанно:
 * по именам видно, сколько у человека профилей, но не что в них.
 */
export type SlotName = string;

/** Что лежит в ячейке. */
export type SlotSnapshot = {
  slot: SlotName;
  /**
   * Версия ячейки. Растёт на единицу с каждой принятой записью и никогда не
   * убывает. Ноль означает «сюда ещё ничего не клали» — и тогда `body` пуст.
   */
  version: number;
  body: SealedBook | null;
  /** Когда сервер принял эту версию. Время сервера, не устройства. */
  updatedAt: string | null;
};

/** Ячейка в перечне: без содержимого, только имя и версия. */
export type SlotSummary = {
  slot: SlotName;
  version: number;
  updatedAt: string | null;
};

/** Запрос на запись: что кладём и поверх какой версии. */
export type PutRequest = {
  /**
   * Версия, которую устройство считает текущей. Для первой записи в пустую
   * ячейку — 0.
   */
  baseVersion: number;
  body: SealedBook;
};

/** Сервер принял: ячейка доросла до новой версии. */
export type PutAccepted = {
  ok: true;
  version: number;
  updatedAt: string;
};

/**
 * Сервер отказал: пока устройство писало, ячейку обогнали.
 *
 * Вместе с отказом возвращается то, что лежит на сервере сейчас, — чтобы
 * устройству не пришлось ходить второй раз. Дальше его дело слить и повторить
 * запись уже поверх этой версии.
 */
export type PutRejected = {
  ok: false;
  reason: "stale";
  current: SlotSnapshot;
};

export type PutResult = PutAccepted | PutRejected;

/** Сервер сказал: такая-то ячейка доросла до такой-то версии. */
export type SlotChanged = {
  slot: SlotName;
  version: number;
};

/**
 * Провод.
 *
 * Интерфейсом, а не готовым классом с fetch внутри, по двум причинам. Первая:
 * проверки должны гонять настоящую логику синхронизации, а не заглушку вокруг
 * сети, — поддельный сервер подставляется сюда и ведёт себя как настоящий,
 * включая отказы. Вторая: до появления службы (06.6) настоящей реализации
 * попросту нет, и притворяться, что она есть, незачем.
 */
export interface SyncTransport {
  /**
   * Какие ячейки вообще есть у этого человека.
   *
   * Без этого свежее устройство не знает, что спрашивать. С одним профилем
   * незаметно — его ячейка называется так же, как на первом устройстве, и
   * находится сама; а вот второй и третий профили не доехали бы никогда, и
   * человек увидел бы, что часть его книг просто пропала при переезде.
   */
  list(): Promise<SlotSummary[]>;

  /** Что лежит в ячейке сейчас. */
  pull(slot: SlotName): Promise<SlotSnapshot>;

  /** Положить поверх известной версии. Может вернуть отказ — это нормально. */
  push(slot: SlotName, request: PutRequest): Promise<PutResult>;

  /**
   * Подписка на изменения: сервер сам говорит, когда ячейку тронуло другое
   * устройство. Возвращает отписку.
   *
   * Подписка — ускорение, а не основа. Соединение рвётся, события теряются, и
   * синхронизация обязана сходиться и без них — на следующем чтении или
   * записи. Поэтому здесь нет ни подтверждений доставки, ни порядковых
   * номеров событий: событие говорит «сходи посмотри», а не «вот данные».
   */
  watch(onChange: (event: SlotChanged) => void): () => void;
}

/**
 * Связи нет.
 *
 * Отдельным классом, потому что для синхронизации это не поломка, а обычное
 * состояние: приложение местное, оно работает без сервера и должно молча
 * складывать отправку в очередь, а не показывать человеку красное. Отличать
 * это от настоящей ошибки сервера по тексту было бы гаданием.
 */
export class OfflineError extends Error {
  constructor(cause?: unknown) {
    super("Нет связи с сервером.", { cause });
    this.name = "OfflineError";
  }
}

export function isOffline(error: unknown): boolean {
  return error instanceof OfflineError;
}

/** Ручки службы — чтобы 06.6 писалась по этому файлу, а не по памяти. */
export const ROUTES = {
  /** GET → { slots: SlotSummary[] } */
  slots: "/vault",
  /** GET → SlotSnapshot */
  slot: (slot: SlotName) => `/vault/${encodeURIComponent(slot)}`,
  /** PUT PutRequest → PutResult (отказ отдаётся кодом 409, а не 200). */
  put: (slot: SlotName) => `/vault/${encodeURIComponent(slot)}`,
  /** GET, поток событий SlotChanged. */
  events: "/events"
} as const;
