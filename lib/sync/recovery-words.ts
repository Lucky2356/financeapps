// Словарь кода восстановления: 1024 слова, ровно 10 бит на слово.
//
// Код восстановления — второй замок на ключе книги, и единственный путь назад
// для человека, забывшего пароль. Его переписывают с бумаги, поэтому список
// собран не по красоте, а по тому, насколько трудно ошибиться при переписывании
// и наборе. Правила проверяются тестом, а не обещанием:
//
//   * только строчная кириллица — и ни одного слова с «ё», потому что его пишут
//     то с точками, то без, и один и тот же код оказывается двумя разными;
//   * от четырёх до восьми букв: короткие сливаются, длинные чаще перевирают;
//   * все слова разные и все различаются уже первыми четырьмя буквами, так что
//     ввод можно принимать по четырём буквам и подсказывать остальное;
//   * ровно 1024 = 2^10 — тогда слово несёт целых десять бит и выбирается из
//     случайных байтов без остатка, без приведения по модулю, которое незаметно
//     сделало бы начало списка чуть вероятнее конца.
//
// Двенадцать слов из этого списка — 120 бит. Для сравнения: ключ книги — 256
// бит, а подбор кода стоит не одну проверку, а целый прогон PBKDF2. Список
