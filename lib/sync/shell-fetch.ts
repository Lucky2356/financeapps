"use client";

// Запрос к ЧУЖОМУ серверу — тому, чей адрес человек вписал сам.
//
// Почему это отдельное место, а не просто fetch.
//
// Собранное приложение живёт под политикой безопасности (CSP), и в ней
// перечислено, куда вкладке разрешено ходить: биржа, ЦБ, GitHub. Список этот
// зашивается в СБОРКУ, а адрес своей службы человек называет во время работы —
// значит его в списке нет и быть не может. Обычный fetch вкладки до такой
// службы не доходит вовсе: WebView гасит запрос ещё до отправки, и снаружи это
// выглядит как «нет связи», без единого слова о настоящей причине.
//
// Ни в одной проверке этого не увидеть. Ни vitest, ни Playwright не применяют
// CSP собранного приложения, поэтому там всё зелено — а на живой машине не
// работает ничего. В памятке по выпуску это записано прямо: «CSP в том виде, в
// каком её применяет WebView2» — среди того, чего проверки не достают.
//
// Обход — не наша выдумка: в приложении уже есть такое место, обновления на
// Android ходят тем же путём (см. lib/updates/android.ts). Запрос выполняет
// Rust, а не вкладка, и политика страницы на него не распространяется.
//
// Чем за это платим, и стоит сказать прямо: плагину разрешено ходить на любой
// HTTPS-адрес. Сузить нельзя — адрес службы произвольный по замыслу. Но
// разрешение это ПЛАГИНУ, а не странице: сам fetch вкладки остаётся запертым,
// и чужой скрипт, попади он в приложение, наружу через него не уйдёт.

import { isTauriShell } from "@/lib/platform/env";

type Fetch = (input: string, init?: RequestInit) => Promise<Response>;

function pageFetch(): Fetch {
  return (input, init) => globalThis.fetch(input, init);
}

/**
 * Выбирается ОДИН раз и запоминается: это разбор окружения, а не решение про
 * конкретный запрос, и повторять его на каждом обращении незачем.
 *
 * Обещание здесь никогда не отклоняется. Откажи оно — запомнился бы отказ, и
 * синхронизация умерла бы навсегда до перезапуска. Поэтому неудача ввоза
 * плагина сводится к обычному fetch: в браузере он и так единственный верный,
 * а в собранном приложении хуже уже не будет.
 */
let chosen: Promise<Fetch> | null = null;

async function pick(): Promise<Fetch> {
  if (!isTauriShell()) return pageFetch();
  try {
    const { fetch: throughRust } = await import("@tauri-apps/plugin-http");
    return throughRust as unknown as Fetch;
  } catch {
    return pageFetch();
  }
}

export function shellFetch(input: string, init?: RequestInit): Promise<Response> {
  chosen ??= pick();
  return chosen.then((go) => go(input, init));
}

/** Только для проверок: забыть сделанный выбор. */
export function forgetShellFetchChoice(): void {
  chosen = null;
}
