// Адрес службы по умолчанию — тот, что зашит в сборку.
//
// ЗАЧЕМ ОН ВООБЩЕ. Без него первый вопрос, который приложение задаёт человеку,
// собравшемуся связать телефон с компьютером, — «адрес вашей службы». У
// человека «с улицы» службы нет, и слова этого он не знает; на этом месте
// разговор и кончается. Зашитый адрес превращает первый вопрос в отсутствие
// вопроса: нажал «связать» — и связалось.
//
// ЧЕГО ЭТО СТОИТ, ПРЯМО. Владелец приложения становится хранителем чужих
// данных. Данные лежат у него зашифрованными, и ключа от них у службы нет —
// но существование учётной записи, её имя входа, размеры и время правок он
// видит (см. SECURITY.md, раздел о том, что служба всё-таки знает). Это цена
// обещания «скачал и работает», и она названа на самом экране подключения, а
// не здесь.
//
// ПОЧЕМУ НЕ ПРОСТО КОНСТАНТА. Приложение собирают и другие люди — для себя, со
// своей службой. Заставлять их править исходник ради одной строки значит
// заставлять их поддерживать свою ветку вечно.

/**
 * Куда приложение предлагает подключиться, если человек не назвал своего
 * адреса.
 *
 * `NEXT_PUBLIC_FINANCE_SERVER` читается на СБОРКЕ, а не на запуске: статический
 * вывод Next подставляет значение прямо в код, и во время работы переменных
 * окружения уже нет. Для того, кто собирает приложение себе, это одна строка в
 * команде сборки; для всех остальных — адрес, на котором служба уже работает.
 *
 * Пустая строка — законное значение и означает «службы по умолчанию нет». Тогда
 * приложение спрашивает адрес, как спрашивало раньше. Собрать себе сборку
 * совсем без предложенной службы — это `NEXT_PUBLIC_FINANCE_SERVER=""`.
 */
const configured = process.env.NEXT_PUBLIC_FINANCE_SERVER;

export const DEFAULT_SERVER =
  configured === undefined
    ? "https://finance.zagranica.online"
    : configured.trim().replace(/\/+$/, "");

/** Есть ли вообще кому предлагать. Пусто — спрашиваем адрес, как раньше. */
export function hasDefaultServer(): boolean {
  return DEFAULT_SERVER !== "";
}

/**
 * Предложенная ли это служба — то есть НЕ называл ли человек адрес сам.
 *
 * Пустой адрес не «совпадает» с пустым умолчанием: сравнение двух пустот
 * вернуло бы true, и приложение назвало бы своей службой ничто. Та же западня,
 * что и с пустой приставкой у первого человека, и ловится она тем же —
 * отдельной проверкой на пустоту, а не обещанием её не допустить.
 */
export function isDefaultServer(base: string): boolean {
  const clean = base.trim().replace(/\/+$/, "");
  return clean !== "" && clean === DEFAULT_SERVER;
}
