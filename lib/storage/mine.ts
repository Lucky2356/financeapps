import { PERSON_MARK } from "@/lib/storage/NamespacedStorageAdapter";

/**
 * Мелочи, которые приложение держит в localStorage, — по одному человеку.
 *
 * localStorage один на всё устройство, и приставки у него нет. Пока человек был
 * один, это ничего не значило; с появлением второго часть того, что там лежит,
 * оказалась чужими данными в общем месте:
 *
 *   tx-saved-filters   сохранённые фильтры — НАЗВАНИЯ КАТЕГОРИЙ И СУММЫ;
 *   auto-backup-config куда и как часто класть копии;
 *   sync-folder        папка, в которую человек кладёт свои данные;
 *   quick-add-*        каким счётом он пользовался последним;
 *   notif-fired        о чём ему уже говорили.
 *
 * Разделяются именно эти. Настройки ВИДА — плотность, свёрнутая колонка,
 * открытая аналитика, язык — остаются общими нарочно: они про окно, а не про
 * человека, и делить их значило бы заставлять каждого настраивать вид заново.
 *
 * Приставка здесь та же, что у хранилища, и это не совпадение: одно устройство,
 * один способ сказать «это моё», и незачем заводить второй, который однажды
 * разойдётся с первым.
 */

/**
 * Кто сейчас за устройством. Пустая строка — первый человек, и это законное
 * значение: его мелочи лежат там же, где лежали, переносить нечего.
 */
let who = "";

/**
 * Запомнить, чьи мелочи читаем.
 *
 * Зовётся один раз, когда выбор человека состоялся. До этого момента приставка
 * пуста — и это безопасно ровно потому, что экраны рисуются ПОСЛЕ ворот, а
 * ворота выбора дожидаются. Случись наоборот, второй человек увидел бы чужие
 * фильтры; поэтому порядок и закреплён в воротах, а не оставлен на удачу.
 */
export function rememberWho(id: string): void {
  who = id;
}

/** Имя ключа этого человека. */
export function mineKey(key: string): string {
  return who ? `${PERSON_MARK}${who}/${key}` : key;
}

/**
 * Читать и писать так же молча, как это делалось раньше.
 *
 * localStorage отказывает в приватном окне и при запрете на запись, и мелочи
 * вроде «какой счёт был последним» не стоят того, чтобы из-за них падал экран.
 * Обёртки здесь затем, чтобы каждое из семи мест не повторяло try/catch и не
 * забывало приставку.
 */
export function readMine(key: string): string | null {
  try {
    return localStorage.getItem(mineKey(key));
  } catch {
    return null;
  }
}

export function writeMine(key: string, value: string): void {
  try {
    localStorage.setItem(mineKey(key), value);
  } catch {
    /* хранилище недоступно — мелочь того не стоит */
  }
}

export function removeMine(key: string): void {
  try {
    localStorage.removeItem(mineKey(key));
  } catch {
    /* хранилище недоступно — мелочь того не стоит */
  }
}

