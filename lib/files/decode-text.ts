/**
 * Текст выбранного файла: UTF-8, а если байты в UTF-8 не складываются — Windows-1251.
 *
 * Выписки российских банков (Сбер, ВТБ, выгрузки из 1С) до сих пор приходят в
 * cp1251. `file.text()` читает только UTF-8 и заменяет всё непонятное на «�»:
 * «Дата операции» превращалась в «���� ��������», колонки не находились, а
 * описания в учёте оставались мусором. Строгий UTF-8 ({ fatal: true }) на таком
 * файле падает почти сразу — русская буква в cp1251 это одиночный байт ≥ 0x80,
 * которого в правильном UTF-8 не бывает, — и это верный знак взять cp1251.
 * Метка BOM в начале UTF-8 отбрасывается, как и раньше у `file.text()`.
 */
export function decodeTextBytes(bytes: ArrayBuffer | Uint8Array): string {
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return new TextDecoder("windows-1251").decode(bytes);
  }
}
