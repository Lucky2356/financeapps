import type { ReactNode } from "react";

import { cn } from "@/lib/utils";

/**
 * Полоса «что-то стоит знать» — факт и то, что с ним можно сделать.
 *
 * Не тревога и не ошибка: приложение работает, просто есть обстоятельство,
 * которое человек хотел бы видеть. Операции, датированные будущим; резервная
 * копия, которой давно не было. Отсюда и вид — одна строка, приглушённая рамка,
 * действие ссылкой, а не кнопкой во всю ширину.
 *
 * Заведено как отдельный компонент после второго такого места: разметка была
 * скопирована слово в слово, и две полосы уже начали бы расходиться по отступам
 * и цвету, оставаясь при этом одним и тем же по смыслу.
 */
export function NoticeLine({
  children,
  testId,
  className
}: {
  children: ReactNode;
  testId?: string;
  className?: string;
}) {
  return (
    <p
      data-testid={testId}
      className={cn(
        "flex flex-wrap items-center gap-x-2 gap-y-1 rounded-md border border-warning/30 bg-warning/10 px-3 py-2 text-sm",
        className
      )}
    >
      {children}
    </p>
  );
}

/**
 * Вид действия внутри полосы. Здесь это класс, а не компонент: в одном месте
 * действие — переход по ссылке, в другом — кнопка, меняющая фильтр на этом же
 * экране. Подменять `<a>` кнопкой ради общего вида значило бы ломать середину
 * клика и клавиатуру, поэтому общим сделано ровно то, что общее, — оформление.
 */
export const NOTICE_ACTION_CLASS = "font-medium text-primary underline underline-offset-4";
