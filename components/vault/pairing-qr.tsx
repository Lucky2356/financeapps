"use client";

// Картинка связки — та же восьмёрка знаков, только для камеры.
//
// ПОЧЕМУ SVG, А НЕ CANVAS. Картинку печатают, увеличивают и показывают с
// экрана телефона на экран телефона; SVG остаётся чётким при любом размере, а
// canvas пришлось бы рисовать под плотность конкретного экрана и переснимать
// при каждом изменении. Заодно SVG видно в проверках: canvas в jsdom пустой
// холст, и проверить было бы нечего.
//
// ПОЧЕМУ ВСЕГДА ЧЁРНОЕ НА БЕЛОМ, ДАЖЕ В ТЁМНОЙ ТЕМЕ. Это не недосмотр темы.
// Читалки QR ожидают тёмные модули на светлом поле; обратную полярность многие
// берут, но не все, и узнать, какая камера попадётся человеку, нельзя. Цена
// белого прямоугольника в тёмной теме — он заметен; цена неузнанного кода —
// человек решает, что связка не работает. Поэтому поле здесь своё, явное, и
// от темы не зависит.
//
// ПОЧЕМУ ВОКРУГ ПУСТО. Четыре модуля тишины по краю — требование самого
// формата. Без них читалка не находит границу кода, и это ровно та поломка,
// которая проявляется не везде: на одном телефоне читается, на другом нет.

import qrcode from "qrcode-generator";
import { useMemo } from "react";

/** Модулей тишины по краю. Меньше нельзя: так устроен формат. */
const QUIET = 4;

export function PairingQr({ value, size = 220 }: { value: string; size?: number }) {
  const drawing = useMemo(() => {
    // Тип 0 — «подбери сам под длину»: ссылка растёт вместе с адресом службы,
    // и закреплять размер значило бы однажды не вместить чей-то длинный адрес.
    // Уровень M — средняя избыточность: код переживает блик и палец на экране,
    // не разрастаясь так, как на уровне H.
    const code = qrcode(0, "M");
    code.addData(value);
    code.make();

    const count = code.getModuleCount();
    const side = count + QUIET * 2;

    // Один путь на все тёмные модули: тысяча отдельных прямоугольников — это
    // тысяча узлов в дереве, и на телефоне это видно.
    let path = "";
    for (let row = 0; row < count; row += 1) {
      for (let col = 0; col < count; col += 1) {
        if (code.isDark(row, col)) {
          path += `M${col + QUIET} ${row + QUIET}h1v1h-1z`;
        }
      }
    }
    return { side, path };
  }, [value]);

  return (
    <svg
      role="img"
      aria-label="Код связки картинкой"
      data-testid="pairing-qr"
      width={size}
      height={size}
      viewBox={`0 0 ${drawing.side} ${drawing.side}`}
      shapeRendering="crispEdges"
      className="rounded-lg border"
    >
      <rect width={drawing.side} height={drawing.side} fill="#ffffff" />
      <path d={drawing.path} fill="#000000" />
    </svg>
  );
}
