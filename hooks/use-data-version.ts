"use client";

import { useEffect, useState } from "react";

import { onDataChanged } from "@/lib/api/data-events";

// Номер, который растёт всякий раз, когда книга изменилась.
//
// Для тех мест, которые читают данные своим useEffect, а не через
// useApiPageData. Таких немало и меньше им не стать: раздел с трендами внутри
// аналитики, счётчик у колокольчика, список правил — им не нужна страница
// целиком, им нужен один свой запрос.
//
// Класть сюда номер и ставить его в зависимости эффекта проще и честнее, чем
// заводить в каждом таком месте свою подписку с отпиской: забыть одну строчку в
// массиве зависимостей трудно, а забыть целый useEffect с onDataChanged —
// легко. Ровно так и вышло: синхронизация уже поднимала экраны, читавшие через
// useApiPageData, а эти оставались с числами, прочитанными при открытии.
//
// Снаружи это выглядело хуже всего: на одном экране приложения одни суммы, на
// другом — другие, и обе прочитаны из одной и той же книги.
export function useDataVersion(): number {
  const [version, setVersion] = useState(0);
  useEffect(() => onDataChanged(() => setVersion((current) => current + 1)), []);
  return version;
}
